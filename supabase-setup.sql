-- Hühnerjagd: globale Highscore-Tabelle
-- In Supabase öffnen: SQL Editor -> New query -> diesen gesamten Inhalt ausführen.

create table if not exists public.huehnerjagd_scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 18),
  score integer not null check (score >= 0 and score <= 1000000),
  created_at timestamptz not null default now()
);

create index if not exists huehnerjagd_scores_score_created_idx
  on public.huehnerjagd_scores (score desc, created_at asc);

alter table public.huehnerjagd_scores enable row level security;

drop policy if exists "Anyone can read leaderboard" on public.huehnerjagd_scores;
create policy "Anyone can read leaderboard"
  on public.huehnerjagd_scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit a score" on public.huehnerjagd_scores;
create policy "Anyone can submit a score"
  on public.huehnerjagd_scores for insert
  to anon, authenticated
  with check (
    char_length(player_name) between 1 and 18
    and score >= 0
    and score <= 1000000
  );

grant select, insert on public.huehnerjagd_scores to anon, authenticated;
grant usage, select on sequence public.huehnerjagd_scores_id_seq to anon, authenticated;
